/*
================================================================================
JUSTIFICACION MATEMATICA DE LA CLAUSULA STORAGE
================================================================================
Método de cálculo utilizado en clase:
  - Tamaño de fila (B) = 3 B de cabecera + por columna (1 B de longitud + dato promedio).
                         NUMBER ~ 2 B por cada 3 dígitos; DATE = 7 B.
  - Espacio necesario  = filas * tamaño de fila / (1 - PCTFREE)
  - INITIAL            = espacio para la carga inicial estimada (1000 filas),
                         redondeado hacia arriba a múltiplo de 64K (extensión mínima).
  - NEXT               = espacio para el crecimiento estimado de 1 año, redondeado a múltiplo de 64K.
  - PCTFREE            = reserva para UPDATE:
                           * 5% tablas que casi no se modifican (CLIENTES, PAGOS)
                           * 10% catálogos y datos maestros (ROLES, MODULOS, TIP_CONTRATO, PERSONA, USUARIOS)
                           * 15% si cambia estado/precio/leído (HABITACIONES, NOTIFICACIONES)
                           * 20% si el registro se actualiza durante su vida (CONTRATO: estado, cierre)
  - PCTINCREASE 0      = extensiones de tamaño constante y predecible (evita fragmentación).
  - SEGMENT CREATION IMMEDIATE = reserva el segmento desde el CREATE TABLE para auditar
                                 en USER_SEGMENTS / DBA_SEGMENTS desde el inicio.

Nota: En tablespaces con gestión local (ASSM, por defecto en Oracle XE/12c+),
Oracle administra automáticamente las listas libres y no requiere PCTUSED.

TABLA DE CALCULO VOLUMETRICO (11 TABLAS DEL ESQUEMA RESIDENCIA_AJ):
--------------------------------------------------------------------------------
Tabla               B/fila  PCTFREE  Carga 1000 filas         INITIAL   Crec./año         NEXT
--------------------------------------------------------------------------------
PERSONA               100     10     97.7 KB / 0.90 = 108 KB   128K     +500  = 54 KB      64K
ROLES                  45     10     43.9 KB / 0.90 =  49 KB    64K     +5    (mínimo)     64K
MODULOS                80     10     78.1 KB / 0.90 =  87 KB   128K     +20   (mínimo)     64K
TIP_CONTRATO           25     10     24.4 KB / 0.90 =  27 KB    64K     +5    (mínimo)     64K
HABITACIONES          105     15    102.5 KB / 0.85 = 121 KB   128K     +50   (mínimo)     64K
CLIENTES               12      5     11.7 KB / 0.95 =  12 KB    64K     +400  (mínimo)     64K
USUARIOS               60     10     58.6 KB / 0.90 =  65 KB   128K     +100  (mínimo)     64K
PERMISOS_ROL_MODULO    25     10     24.4 KB / 0.90 =  27 KB    64K     +100  (mínimo)     64K
NOTIFICACIONES         65     15     63.5 KB / 0.85 =  75 KB   128K     +5000 = 373 KB    384K
CONTRATO               90     20     87.9 KB / 0.80 = 110 KB   128K     +1000 = 110 KB    128K
PAGOS                  65      5     63.5 KB / 0.95 =  67 KB   128K     +6000 = 401 KB    448K
--------------------------------------------------------------------------------
Los índices PK/UNIQUE guardan ~10 B por entrada: 1000 entradas = 10 KB, por eso se
fijan en INITIAL 64K NEXT 64K (extensión mínima).
================================================================================
*/

-- 1. PERSONA
CREATE TABLE PERSONA (
    id_persona    INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombres       VARCHAR2(50) NOT NULL,
    ap_paterno    VARCHAR2(50) NOT NULL,
    ap_materno    VARCHAR2(50),
    nro_documento CHAR(8)      NOT NULL,
    telefono      CHAR(9),
    email         VARCHAR2(50),
    fecha_nac     DATE,
    CONSTRAINT pk_persona PRIMARY KEY (id_persona)
        USING INDEX STORAGE (INITIAL 64K NEXT 64K)
)
SEGMENT CREATION IMMEDIATE
PCTFREE 10
TABLESPACE USERS
STORAGE (INITIAL 128K NEXT 64K MINEXTENTS 1 MAXEXTENTS UNLIMITED PCTINCREASE 0);

