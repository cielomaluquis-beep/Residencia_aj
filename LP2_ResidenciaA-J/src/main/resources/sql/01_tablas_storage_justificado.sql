-- 1. Recolectar estadísticas del esquema y comparar tamaño estimado vs real
-- EXEC DBMS_STATS.GATHER_SCHEMA_STATS('RESIDENCIA_AJ');
SELECT T.TABLE_NAME,
       T.NUM_ROWS,
       T.AVG_ROW_LEN,
       ROUND(T.NUM_ROWS * T.AVG_ROW_LEN / 1024) AS KB_DATOS,
       T.PCT_FREE,
       T.INITIAL_EXTENT / 1024 AS INITIAL_KB,
       T.NEXT_EXTENT    / 1024 AS NEXT_KB,
       S.BYTES / 1024          AS KB_REAL,
       S.EXTENTS,
       S.BLOCKS
FROM USER_TABLES T
JOIN USER_SEGMENTS S ON S.SEGMENT_NAME = T.TABLE_NAME AND S.SEGMENT_TYPE = 'TABLE'
ORDER BY T.TABLE_NAME;

